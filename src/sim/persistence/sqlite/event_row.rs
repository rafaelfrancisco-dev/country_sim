pub(super) fn load_events(
    conn: &Connection,
    owner_scope: &str,
    owner_country_id: i64,
) -> Result<Vec<SimEventDto>, PersistenceError> {
    let mut stmt = conn.prepare(
        "SELECT
            event_kind, day, entity_kind, bank_kind, ipo_reason, country_name,
            from_country_name, to_country_name, home_country_name, foreign_country_name,
            currency_code, company_name, bank_name, acquired_by_bank_name, ticker,
            disaster_label, summary, count, entity_id, person_id, company_id, bank_id,
            acquired_by_bank_id, from_company_id, to_company_id,
            produced_good_id, founders, job_type_id, intensity_pct, months_unemployed,
            months_on_benefits, total_recipients, entities_affected, migrated_depositors,
            migrated_companies, migrated_loans, quits, retirements, layoffs_non_distress,
            replacement_openings, laid_off_count, listed_count, shares_issued,
            primary_shares_issued, secondary_shares_sold, shares_liquidated, shares_wiped,
            principal, principal_lost, unpaid_amount, total_amount, total_funding,
            treasury_funding, deficit_funding, seed_capital, health, requested,
            haircut_loss, treasury_support, amount_lost, cut_rate, monthly_salary,
            principal_written_off, price_per_share, total_raised, primary_raised,
            secondary_raised, founder_payout_total, per_share, proceeds, total_market_cap,
            total_turnover, new_rate, old_rate, inflation_rate, unemployment_rate,
            face_value, coupon_rate, total_coupon, shortfall, monetized, amount,
            inflation_shortfall, unemployment_gap, price, home_amount, foreign_amount,
            fx_rate_home_per_foreign, annual_rate, returned_home_amount,
            returned_foreign_amount, reserves_base, reserve_gap, pressure, new_price_index,
            change_pct, amount_due, amount_paid, transferred_reserves
         FROM events
         WHERE owner_scope=?1 AND owner_country_id=?2
         ORDER BY event_seq",
    )?;
    let rows = stmt.query_map(params![owner_scope, owner_country_id], sim_event_from_row)?;
    let mut events = Vec::new();
    for row in rows {
        events.push(row?);
    }
    Ok(events)
}

